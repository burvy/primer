//! `primer-server voices`: keeps Ada's recordings in order.
//!
//! One command does three things:
//! 1. Finds every line Ada reads aloud (from the checked content).
//! 2. Makes a placeholder recording for each line that has neither a real
//!    recording nor a placeholder yet. It never overwrites a file.
//! 3. Writes `assets/voice/RECORDINGS.md`: the list to hand a voice actor,
//!    with each line's file name, look, exact words, and status.
//!
//! To replace a placeholder, drop a real recording named like the line, with
//! `.ogg`, `.mp3` or `.wav`, into `assets/voice/` and run the command again:
//! the status turns to `recorded`.
//!
//! The placeholder voices come from Windows' own speech (see
//! `tools/voice/placeholders.ps1`). On another system the command still
//! writes the list; the page then falls back to the browser's voice.

use std::path::Path;
use std::process::Command;

use crate::content::Content;
use crate::content::voice::Line;

/// Where a line's audio stands.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Status {
    /// A real recording is in `assets/voice/`.
    Recorded,
    /// Only the computer-voiced placeholder exists.
    Placeholder,
    /// Neither exists yet.
    Missing,
}

impl Status {
    fn word(self) -> &'static str {
        match self {
            Status::Recorded => "recorded",
            Status::Placeholder => "placeholder",
            Status::Missing => "missing",
        }
    }
}

/// The file types a real recording may have. The page tries them in this order.
pub const RECORDING_TYPES: [&str; 3] = ["ogg", "mp3", "wav"];

/// The status of the line called `name`.
///
/// `exists` answers "is there a file at this path inside `assets/voice/`?",
/// so the rule can be tested without touching the disk.
pub fn status(exists: impl Fn(&str) -> bool, name: &str) -> Status {
    if RECORDING_TYPES
        .iter()
        .any(|kind| exists(&format!("{name}.{kind}")))
    {
        Status::Recorded
    } else if exists(&format!("placeholder/{name}.wav")) {
        Status::Placeholder
    } else {
        Status::Missing
    }
}

/// The recordings list as a Markdown table, one row per line.
pub fn recordings_md(rows: &[(&Line, Status)]) -> String {
    let mut md = String::from(
        "# Recordings\n\
         \n\
         Generated by `cargo run -p primer-server -- voices`. Do not edit by hand:\n\
         changes are overwritten the next time it runs.\n\
         \n\
         **For the voice actor.** Read each line in the *Text to read* column, in a\n\
         warm, clear, unhurried voice, as Ada talking to a child. Save it as\n\
         `<File name>.ogg` (or `.mp3` or `.wav`), exactly as spelled in the first\n\
         column. The *Look* column says which book the line is for: `gentle` is the\n\
         storybook, `exceptional` is the grown-up treatise. Lines are in book order.\n\
         \n\
         **To use a recording**, put the file in `assets/voice/` and run the command\n\
         again. The page plays a real recording first, then the placeholder, then\n\
         the browser's own voice.\n\
         \n\
         | File name | Look | Text to read | Status |\n\
         |---|---|---|---|\n",
    );
    for (line, status) in rows {
        // A `|` inside the text would break the table.
        let text = line.speech.replace('|', "\\|");
        md.push_str(&format!(
            "| `{}` | {} | {} | {} |\n",
            line.name,
            line.look,
            text,
            status.word()
        ));
    }
    md
}

/// The to-do file for the placeholder script: name, a tab, the words.
pub fn todo_list(lines: &[&Line]) -> String {
    lines
        .iter()
        .map(|line| format!("{}\t{}\n", line.name, line.speech))
        .collect()
}

/// Looks at the disk for each line's status.
fn statuses<'a>(lines: &'a [Line], voice_dir: &Path) -> Vec<(&'a Line, Status)> {
    lines
        .iter()
        .map(|line| {
            let found = status(|file| voice_dir.join(file).is_file(), &line.name);
            (line, found)
        })
        .collect()
}

/// Runs the command. `assets` is the assets folder; `script` is the
/// PowerShell file that makes placeholders.
pub fn run(content: &Content, assets: &Path, script: &Path) -> Result<(), String> {
    let voice_dir = assets.join("voice");
    let placeholders = voice_dir.join("placeholder");
    std::fs::create_dir_all(&placeholders).map_err(|e| format!("{}: {e}", placeholders.display()))?;

    let missing: Vec<&Line> = statuses(&content.lines, &voice_dir)
        .into_iter()
        .filter(|(_, status)| *status == Status::Missing)
        .map(|(line, _)| line)
        .collect();
    if missing.is_empty() {
        println!("no placeholders to make");
    } else {
        println!("making {} placeholder(s)...", missing.len());
        make_placeholders(&missing, &placeholders, script);
    }

    let rows = statuses(&content.lines, &voice_dir);
    let count = |wanted| rows.iter().filter(|(_, s)| *s == wanted).count();
    let list = voice_dir.join("RECORDINGS.md");
    std::fs::write(&list, recordings_md(&rows)).map_err(|e| format!("{}: {e}", list.display()))?;
    println!(
        "{}: {} recorded, {} placeholder, {} missing",
        list.display(),
        count(Status::Recorded),
        count(Status::Placeholder),
        count(Status::Missing)
    );
    Ok(())
}

/// Asks PowerShell to voice each line. A failure is reported, not fatal:
/// the list is still written, and the page falls back to the browser's voice.
fn make_placeholders(lines: &[&Line], out: &Path, script: &Path) {
    let todo = std::env::temp_dir().join("primer-voice-todo.tsv");
    if let Err(error) = std::fs::write(&todo, todo_list(lines)) {
        println!("cannot write {}: {error}", todo.display());
        return;
    }
    let result = Command::new("powershell")
        .args(["-NoProfile", "-ExecutionPolicy", "Bypass", "-File"])
        .arg(script)
        .arg("-List")
        .arg(&todo)
        .arg("-Out")
        .arg(out)
        .status();
    match result {
        Ok(status) if status.success() => {}
        Ok(status) => println!("the placeholder script stopped: {status}"),
        Err(error) => println!("could not run powershell ({error}); no placeholders made"),
    }
    let _ = std::fs::remove_file(&todo);
}

#[cfg(test)]
mod tests {
    use super::*;

    fn line(name: &str, look: &'static str, speech: &str) -> Line {
        Line {
            name: name.into(),
            look,
            speech: speech.into(),
        }
    }

    #[test]
    fn a_real_recording_beats_a_placeholder() {
        let both = |file: &str| file == "x.mp3" || file == "placeholder/x.wav";
        assert_eq!(status(both, "x"), Status::Recorded);
        assert_eq!(status(|f| f == "placeholder/x.wav", "x"), Status::Placeholder);
        assert_eq!(status(|_| false, "x"), Status::Missing);
        // A placeholder-named file in the main folder is not a recording of `y`.
        assert_eq!(status(|f| f == "x.ogg", "y"), Status::Missing);
    }

    #[test]
    fn the_list_has_one_row_per_line_with_status() {
        let a = line("l.1.1.gentle", "gentle", "Three plus four.");
        let b = line("l.1.1.exceptional", "exceptional", "a | b");
        let md = recordings_md(&[(&a, Status::Placeholder), (&b, Status::Recorded)]);
        assert!(md.contains("| `l.1.1.gentle` | gentle | Three plus four. | placeholder |"), "{md}");
        assert!(md.contains("| `l.1.1.exceptional` | exceptional | a \\| b | recorded |"), "{md}");
    }

    #[test]
    fn the_to_do_file_is_name_tab_words() {
        let a = line("n", "gentle", "Hello there.");
        assert_eq!(todo_list(&[&a]), "n\tHello there.\n");
    }
}
